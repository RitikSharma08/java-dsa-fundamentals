   //Assignment operator example ..
public class Assignment {
    public static void main(String[] args) {
        int a;
        a=10; //simple
        System.out.println(a);   //10

        a+=10; // compound (a=a+10)
        System.out.println(a);   //20

        a-=10; //compund (a=a-10)
        System.out.println(a);   //10

    }
    
}
